const {createHash} = require('node:crypto');
const MARKER = '// Generated by Automated Quality Gate; review before merging.\n';
const COMMIT_MESSAGE = 'chore(quality-gate): save generated tests [aq-generated]';
const allowed = name => /^Test\/quality-gate\/[a-f0-9]{16}\.test\.js$/.test(name) || name === 'quality-gate/generated.test.cjs';

async function publishTests(api, repository, number, expectedHead, files, conclusion) {
  const prefix = `/repos/${repository}`;
  const entries = Object.entries(files);
  if (!entries.length || entries.length > 20 || entries.some(([name,text]) => !allowed(name) || typeof text !== 'string' || !text.startsWith(MARKER) || Buffer.byteLength(text)>100000)) throw new Error('Generated test files failed publication validation');
  const pull = await api(`${prefix}/pulls/${number}`);
  const repo = await api(prefix);
  if (pull.state !== 'open' || pull.head.repo?.full_name !== repository || pull.head.ref === repo.default_branch || pull.head.ref === pull.base.ref) throw new Error('Tests can only be saved to an open same-repository PR branch, never the default branch');
  if (pull.head.sha !== expectedHead) throw new Error('PR changed during analysis; rerun against the latest commit before saving tests');
  const head = await api(`${prefix}/git/commits/${expectedHead}`);
  const tree = await api(`${prefix}/git/trees/${head.tree.sha}?recursive=1`);
  if (tree.truncated) throw new Error('Cannot verify complete PR tree');
  const changes = [];
  for (const [name,text] of entries) {
    const old = tree.tree.find(entry => entry.path === name);
    if (old) {
      if (old.type !== 'blob' || old.mode !== '100644' || (old.size || 0) > 100000) throw new Error('Generated test path is not a regular bounded file');
      const blob = await api(`${prefix}/git/blobs/${old.sha}`);
      if (blob.encoding !== 'base64') throw new Error('Cannot read existing generated test');
      const before = Buffer.from(blob.content,'base64').toString('utf8');
      if (!before.startsWith(MARKER)) throw new Error('Refusing to overwrite a test not owned by Quality Gate');
      if (before === text) continue;
    }
    changes.push({path:name,mode:'100644',type:'blob',content:text});
  }
  let sha = expectedHead;
  if (changes.length) {
    const nextTree = await api(`${prefix}/git/trees`,'POST',{base_tree:head.tree.sha,tree:changes});
    const commit = await api(`${prefix}/git/commits`,'POST',{message:COMMIT_MESSAGE,tree:nextTree.sha,parents:[expectedHead]});
    // The Git ref API refuses a racing, non-fast-forward update. Never force-push.
    await api(`${prefix}/git/refs/heads/${encodeURIComponent(pull.head.ref)}`,'PATCH',{sha:commit.sha,force:false});
    sha = commit.sha;
  }
  // The saved tree adds exactly the tested generated files to the analyzed source.
  // Expose the result on the new head, since bot commits may not start another run.
  await recordCheck(api,repository,sha,conclusion,`Analyzed source: ${expectedHead}\nGenerated tests saved for review: ${entries.length}. Merge this PR to retain them on the base branch.`);
  return {sha,changed:changes.length,digest:createHash('sha256').update(JSON.stringify(entries)).digest('hex')};
}
async function recordCheck(api,repository,sha,conclusion,summary) {
  await api(`/repos/${repository}/check-runs`,'POST',{name:'Quality Gate',head_sha:sha,status:'completed',conclusion,
    output:{title:conclusion === 'success' ? 'Quality checks passed' : 'Quality checks failed or incomplete',summary}});
}
module.exports = {publishTests,recordCheck,MARKER,COMMIT_MESSAGE,allowed};
